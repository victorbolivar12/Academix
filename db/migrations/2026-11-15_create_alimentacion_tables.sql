-- Módulo Alimentación: catálogo de alimentos con calorías por 100 g
-- y registros de comidas (desayuno, almuerzo y cena) por día.

CREATE TABLE IF NOT EXISTS `alimentacion_alimentos` (
  `id` int unsigned NOT NULL AUTO_INCREMENT,
  `nombre` varchar(150) NOT NULL,
  `categoria` varchar(50) NOT NULL,
  `calorias_por_100g` decimal(7,2) NOT NULL,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_alimentacion_alimentos_nombre` (`nombre`),
  KEY `idx_alimentacion_alimentos_categoria` (`categoria`),
  CONSTRAINT `chk_alimentacion_alimentos_calorias` CHECK (`calorias_por_100g` >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `alimentacion_registros` (
  `id` int unsigned NOT NULL AUTO_INCREMENT,
  `fecha` date NOT NULL,
  `tipo_comida` varchar(20) NOT NULL,
  `alimento_id` int unsigned DEFAULT NULL,
  `nombre` varchar(150) NOT NULL,
  `calorias_por_100g` decimal(7,2) NOT NULL,
  `gramos` decimal(7,2) NOT NULL,
  `calorias` decimal(9,2) NOT NULL,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_alimentacion_registros_fecha` (`fecha`),
  KEY `idx_alimentacion_registros_fecha_comida` (`fecha`, `tipo_comida`),
  KEY `idx_alimentacion_registros_alimento` (`alimento_id`),
  CONSTRAINT `fk_alimentacion_registros_alimento`
    FOREIGN KEY (`alimento_id`) REFERENCES `alimentacion_alimentos` (`id`)
    ON DELETE SET NULL,
  CONSTRAINT `chk_alimentacion_registros_tipo`
    CHECK (`tipo_comida` IN ('desayuno', 'almuerzo', 'cena')),
  CONSTRAINT `chk_alimentacion_registros_gramos` CHECK (`gramos` > 0),
  CONSTRAINT `chk_alimentacion_registros_calorias` CHECK (`calorias` >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

